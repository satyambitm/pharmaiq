"""Deterministic demo initialisation (no model training).

    python scripts/bootstrap_demo.py                  # verify sample data + model bundle
    python scripts/bootstrap_demo.py --load-db        # ...and load PostgreSQL at DATABASE_URL
    python scripts/bootstrap_demo.py --write-seed-sql # regenerate sql/seed.sql from the sample CSV

Steps
1. Regenerate the clean dataset in memory with the fixed seed and check it is byte-identical
   to the bundled `data/sample/synthetic_sales_clean.csv`.
2. Check every file in `models/manifest.json` against its recorded SHA-256 and load the bundle.
3. Optionally load the CSV into PostgreSQL (idempotent: delete-then-insert in one transaction,
   followed by exact reconciliation of counts and money totals).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ml import bundle  # noqa: E402
from ml.model_loader import load_bundle  # noqa: E402
from src import config  # noqa: E402
from src.data.generate import CSV_COLUMNS, generate_clean  # noqa: E402

SAMPLE_CSV = ROOT / "data" / "sample" / "synthetic_sales_clean.csv"
SEED_SQL = ROOT / "sql" / "seed.sql"
logger = logging.getLogger("bootstrap_demo")


def verify_sample() -> str:
    expected = generate_clean(config.RANDOM_SEED).to_csv(index=False, lineterminator="\n").encode("utf-8")
    actual = SAMPLE_CSV.read_bytes()
    if hashlib.sha256(actual).hexdigest() != hashlib.sha256(expected).hexdigest():
        raise SystemExit(f"{SAMPLE_CSV.name} does not match the seed-{config.RANDOM_SEED} generator output")
    digest = hashlib.sha256(actual).hexdigest()
    logger.info("Sample data OK: %s rows, sha256 %s", actual.count(b"\n") - 1, digest[:12])
    return digest


def verify_bundle() -> None:
    manifest = json.loads(bundle.MANIFEST.read_text(encoding="utf-8"))
    for f in manifest["files"]:
        path = bundle.MODELS / f["path"]
        if not path.exists() or bundle.sha256(path) != f["sha256"]:
            raise SystemExit(f"Model bundle file missing or changed: {f['path']}")
    b = load_bundle(bundle.MODELS)
    logger.info("Model bundle OK: %d files, %.2f MB, xgboost %s", len(manifest["files"]),
                manifest["total_bytes"] / 1e6, b.xgb_meta["model_version"])


def load_db() -> None:
    from backend.app.core.config import Settings
    from src.data.load import load_clean
    from sqlalchemy import create_engine

    url = Settings(data_backend="postgres").sqlalchemy_url
    report = load_clean(create_engine(url, pool_pre_ping=True), csv_path=SAMPLE_CSV, report_path=None)
    if not report["reconciled"]:
        raise SystemExit("Database totals do not reconcile with the sample CSV")
    logger.info("Database loaded and reconciled: %d rows", report["db_rows"])


def _sql_value(v: str, col: str) -> str:
    if col in {"month_start", "region_id", "product_id", "data_source"}:
        return "'" + v.replace("'", "''") + "'"
    if col == "campaign_flag":
        return "TRUE" if v.strip().lower() in {"true", "1"} else "FALSE"
    return v


def write_seed_sql() -> None:
    df = pd.read_csv(SAMPLE_CSV, dtype=str, keep_default_na=False)
    lines = [
        "-- Generated by scripts/bootstrap_demo.py --write-seed-sql from data/sample/synthetic_sales_clean.csv.",
        "-- Synthetic demo data (synthetic_v1, seed 42). Run after sql/schema.sql. Safe to re-run.",
        "BEGIN;",
        "INSERT INTO regions (region_id, region_name) VALUES",
        ",\n".join(f"  ('{k}', '{v}')" for k, v in config.REGIONS.items()),
        "ON CONFLICT (region_id) DO UPDATE SET region_name = EXCLUDED.region_name;",
        "INSERT INTO products (product_id, product_name, therapeutic_group) VALUES",
        ",\n".join(f"  ('{k}', '{v}', '{config.THERAPEUTIC_GROUP[k]}')" for k, v in config.PRODUCTS.items()),
        "ON CONFLICT (product_id) DO UPDATE SET product_name = EXCLUDED.product_name, "
        "therapeutic_group = EXCLUDED.therapeutic_group;",
        f"DELETE FROM monthly_sales WHERE data_source = '{config.DATA_SOURCE}';",
        f"INSERT INTO monthly_sales ({', '.join(CSV_COLUMNS)}) VALUES",
        ",\n".join("  (" + ", ".join(_sql_value(row[c], c) for c in CSV_COLUMNS) + ")"
                   for row in df.to_dict("records")) + ";",
        "COMMIT;",
        "",
    ]
    SEED_SQL.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    logger.info("Wrote %s (%d rows)", SEED_SQL.relative_to(ROOT), len(df))


def main() -> None:
    config.setup_logging()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--load-db", action="store_true", help="load PostgreSQL at DATABASE_URL")
    p.add_argument("--write-seed-sql", action="store_true", help="regenerate sql/seed.sql")
    args = p.parse_args()
    verify_sample()
    verify_bundle()
    if args.write_seed_sql:
        write_seed_sql()
    if args.load_db:
        load_db()


if __name__ == "__main__":
    main()
